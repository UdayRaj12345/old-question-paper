CREATE TABLE papers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description VARCHAR(1000) NULL,
  university INT UNSIGNED NULL,
  college INT UNSIGNED NULL,
  department INT UNSIGNED NULL,
  course INT UNSIGNED NULL,
  schoolClass INT UNSIGNED NULL,
  branch VARCHAR(255) NULL,
  semester INT NOT NULL,
  subject INT UNSIGNED NOT NULL,
  subjectCode VARCHAR(100) NULL,
  examType VARCHAR(50) NOT NULL DEFAULT 'End Term',
  academicYear VARCHAR(9) NOT NULL,
  examYear INT NOT NULL,
  language VARCHAR(100) NOT NULL DEFAULT 'English',
  duration INT NULL,
  maximumMarks INT NULL,
  pdfURL VARCHAR(1000) NOT NULL,
  originalFileName VARCHAR(255) NULL,
  public_id VARCHAR(255) NULL,
  resource_type VARCHAR(50) NOT NULL DEFAULT 'raw',
  type VARCHAR(50) NOT NULL DEFAULT 'upload',
  thumbnail VARCHAR(1000) NULL,
  downloads INT NOT NULL DEFAULT 0,
  views INT NOT NULL DEFAULT 0,
  rating DECIMAL(3,2) NOT NULL DEFAULT 0,
  uploadedBy INT UNSIGNED NOT NULL,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  status ENUM('Pending','Approved','Rejected') NOT NULL DEFAULT 'Pending',
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_papers_subject_year_type (subject, academicYear, examType),
  INDEX idx_papers_course_semester (course, semester),
  INDEX idx_papers_title (title),
  CONSTRAINT fk_papers_university FOREIGN KEY (university) REFERENCES universities(id),
  CONSTRAINT fk_papers_college FOREIGN KEY (college) REFERENCES colleges(id),
  CONSTRAINT fk_papers_department FOREIGN KEY (department) REFERENCES departments(id),
  CONSTRAINT fk_papers_course FOREIGN KEY (course) REFERENCES courses(id),
  CONSTRAINT fk_papers_subject FOREIGN KEY (subject) REFERENCES subjects(id),
  CONSTRAINT fk_papers_uploader FOREIGN KEY (uploadedBy) REFERENCES users(id)
);
